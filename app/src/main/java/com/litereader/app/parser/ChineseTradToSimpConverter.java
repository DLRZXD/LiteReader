    public static String convertToSimplified(String text) {
        if (text == null || text.isEmpty()) return text != null ? text : "";
        try {
            if (text.length() >= 64 && text.length() <= 120000) {
                String key = text.hashCode() + "|" + text.length() + "|" + text.charAt(0) + "|" + text.charAt(text.length() - 1);
                String cached = CONVERTED_TEXT_CACHE.get(key);
                if (cached != null) {
                    return cached;
                }
                String converted = performConversionInternal(text);
                CONVERTED_TEXT_CACHE.put(key, converted);
                return converted;
            }
            return performConversionInternal(text);
        } catch (Throwable ignored) {
            return text;
        }
    }

    public static String performConversionInternal(String input) {
        if (input == null || input.isEmpty()) return "";
        int len = input.length();
        char[] out = null;
        for (int i = 0; i < len; i++) {
            char c = input.charAt(i);
            char mapped = CHAR_MAP[c];
            if (mapped != c) {
                if (out == null) {
                    out = input.toCharArray();
                }
                out[i] = mapped;
            }
        }
        if (out == null) {
            return input;
        }
        String s = new String(out);
        for (String[] pf : POST_PHRASE_FIXES) {
            if (s.indexOf(pf[0].charAt(0)) >= 0 && s.contains(pf[0])) {
                s = s.replace(pf[0], pf[1]);
            }
        }
        return s;
    }
